/** Stable id for a built-in exercise row: "chest:barbell-bench-press". */
export const exerciseId = (group: MuscleGroup, name: string) =>
  `${group.toLowerCase().replace(/\s+/g, '-')}:${name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;
